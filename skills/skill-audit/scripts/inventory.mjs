#!/usr/bin/env node
// Cross-skill view for an audit: every skill in scope, whether it may be edited, same-named skills elsewhere, and
// description pairs likely to compete for the same requests. Collision pairs are candidates for judgment, not verdicts.
// Usage: node inventory.mjs [path ...]
// With no paths the scope is everything installed: ~/.claude/skills, ~/.agents/skills, ./skills, ./.claude/skills,
// ./.agents/skills and the skills of installed Claude Code plugins (always report-only). With paths (one new skill,
// say) the scope is those paths, and everything installed is still read as neighbours, so a narrow audit checks the
// scoped skills against the whole collection. Neighbours are never listed as editable.
import {readFileSync,readdirSync,existsSync,realpathSync,statSync} from 'node:fs';
import {join,relative,resolve} from 'node:path';
import {homedir} from 'node:os';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';
import {frontmatter,findSkills} from './lint-skills.mjs';

// Explicit do-not-edit markers, read only from the frontmatter and the first lines of the body: "DO NOT EDIT.",
// "do not hand-edit;", "never edit this file", "not be hand-edited", "Regenerated by ...". Prose about generated
// code ("ignoring auto-generated files") or about editing something else ("do not edit the config directly") does not count.
const GENERATED=/\b(do not|don't|never) (hand-)?edit(?= this (file|skill)\b| by hand\b|\s*[.,;:!—–-]|\s*$)|\bnot be hand-edited|\bregenerated by\b/im;
// Host-managed locations; a Git work tree is never managed, even when laid out as plugins/<p>/skills/<s>.
const MANAGED=/\/\.claude\/plugins\/|\/\.claude\/skills\/synced\/|\/\.(codex|agents)\/skills\/\.system\//;
const STOP=new Set('a an and or the of to in on for with by from as at is are be it its this that these those use used when whenever user users asks ask wants want e.g eg do does not don t skill skills such any all also only into than then via work works their them they which who what how should can will may must one more other others like make sure even explicitly'.split(' '));
const words=(text)=>new Set(text.toLowerCase().replace(/"[^"]*"|“[^”]*”/g,' ').match(/[a-z][a-z0-9-]{2,}/g)?.filter((w)=>!STOP.has(w)).map((w)=>w.replace(/(ing|ed|es|s|e)$/,'')).filter((w)=>!STOP.has(w)&&w.length>2)??[]);
const quoted=(text)=>new Set([...text.matchAll(/"([^"]{3,})"|“([^”]{3,})”/g)].map((m)=>(m[1]??m[2]).toLowerCase().replace(/^[/$]/,'')));

function digest(folder){
 const hash=createHash('sha256');
 const walk=(dir)=>{for(const name of readdirSync(dir).sort()){const path=join(dir,name),stat=statSync(path);if(stat.isDirectory())walk(path);else hash.update(relative(folder,path)).update(readFileSync(path));}};
 walk(folder);return hash.digest('hex').slice(0,12);
}
const inGit=(dir)=>{try{return execFileSync('git',['-C',dir,'rev-parse','--show-toplevel'],{encoding:'utf8',stdio:['ignore','pipe','ignore']}).trim();}catch{return null;}};

// Skill folders of installed Claude Code plugins, from the host's own registry.
export function pluginRoots(home=homedir()){
 try{
  const registry=JSON.parse(readFileSync(join(home,'.claude/plugins/installed_plugins.json'),'utf8'));
  return Object.values(registry.plugins??{}).flat().map((p)=>join(p.installPath,'skills')).filter((path)=>existsSync(path));
 }catch{return [];}
}

export function defaultRoots(home=homedir(),cwd=process.cwd()){
 return [join(home,'.claude/skills'),join(home,'.agents/skills'),...['skills','.claude/skills','.agents/skills'].map((path)=>resolve(cwd,path)),...pluginRoots(home)];
}

export function inventory(roots,neighbourRoots=[]){
 const seen=new Set(),skills=[];
 const load=(root,inScope)=>{for(const folder of findSkills(root,4)){
  // A symlinked install and its target are one skill; a folder in scope is never also a neighbour.
  const real=realpathSync(folder);if(seen.has(real))continue;seen.add(real);
  const source=readFileSync(join(folder,'SKILL.md'),'utf8'),parsed=frontmatter(source),meta=parsed?.meta??{};
  const head=`${source.slice(0,source.length-(parsed?.body.length??source.length))}${(parsed?.body??source).split('\n').slice(0,15).join('\n')}`;
  const repo=inGit(real);
  skills.push({name:String(meta.name||folder.split('/').pop()),description:String(meta.description??'').replace(/\s+/g,' ').trim(),
   folder,root,real,repo,inScope,digest:digest(real),bodyWords:words(parsed?.body??source),generated:GENERATED.test(head),managed:!repo&&MANAGED.test(`${real}/`)});
 }};
 for(const root of roots.filter((path)=>existsSync(path)))load(root,true);
 for(const root of neighbourRoots.filter((path)=>existsSync(path)))load(root,false);
 // Two same-named skills are copies of one skill only on evidence: identical content, or a description or SKILL.md
 // body that mostly matches. A rewritten description alone (this audit's usual change) keeps the body, so an
 // install left behind by it still counts as a copy.
 const jaccard=(x,y)=>[...x].filter((w)=>y.has(w)).length/(new Set([...x,...y]).size||1);
 const related=(a,b)=>a.digest===b.digest||jaccard(words(a.description),words(b.description))>=0.5||jaccard(a.bodyWords,b.bodyWords)>=0.5;
 for(const skill of skills){
  // An unrelated same-named skill never makes another report-only; the same-name line reports the clash instead.
  const twins=skills.filter((other)=>other!==skill&&other.name===skill.name&&related(skill,other));
  const source=!skill.repo&&twins.find((other)=>other.repo);
  // The same skill installed in several places outside Git is almost always a copy of a source kept elsewhere.
  const copies=!skill.repo&&!source&&twins.filter((other)=>!other.repo&&!other.managed&&!other.generated);
  skill.status=skill.generated?'report-only: generated, fix the generator'
   :skill.managed?'report-only: synced or plugin-managed, fix upstream'
   :source?`report-only: installed copy of ${source.folder} (${source.digest===skill.digest?'identical':'diverged'}); fix the source and reinstall`
   :copies?.length?`report-only: also installed at ${copies.map((c)=>c.folder).join(', ')}; add its source repository to the scope, or confirm these copies are the source`
   :'editable';
 }
 // A scoped skill sharing its name with a differing skill elsewhere. Plugin and synced skills are namespaced and
 // coexist; copies of one skill have drifted; unrelated skills shadow each other, since hosts load one per name.
 const sameName=skills.filter((s)=>s.inScope).flatMap((s)=>skills.filter((o)=>o!==s&&o.name===s.name&&o.digest!==s.digest&&!(o.inScope&&o.real<s.real))
  .map((o)=>({name:s.name,a:s.folder,b:o.folder,effect:o.managed||s.managed?'namespaced, both load'
   // Against a repository skill, an unrelated-looking install may still be a heavily edited copy: the user decides.
   :!related(s,o)&&(s.repo||o.repo)?'shares only the name with the repository skill; ask the user whether it is a stale copy (reinstall) or a different skill (rename)'
   :!related(s,o)?'different skill with the same name; only one loads per host; propose a rename'
   :s.repo&&!o.repo?'stale installed copy of this repository skill; reinstall after the audit'
   :o.repo&&!s.repo?'installed copy of a repository skill; fix it there and reinstall'
   :'drifted copies of one skill; confirm which is the source'})));
 // Identical installed copies of a scoped skill: they go stale once the audit edits it.
 const copies=skills.filter((s)=>s.inScope).map((s)=>({name:s.name,folder:s.folder,paths:skills.filter((o)=>!o.inScope&&o.name===s.name&&o.digest===s.digest).map((o)=>o.folder)})).filter((c)=>c.paths.length);
 // One description per name for collisions, preferring the scoped, editable copy.
 const rank=(s)=>(s.inScope?2:0)+(s.status==='editable'?1:0),byName=new Map();
 for(const skill of skills)if(!byName.has(skill.name)||rank(skill)>rank(byName.get(skill.name)))byName.set(skill.name,skill);
 const unique=[...byName.values()],collisions=[];
 for(let i=0;i<unique.length;i++)for(let j=i+1;j<unique.length;j++){
  // Pairs of two neighbours belong to some other audit.
  if(!unique[i].inScope&&!unique[j].inScope)continue;
  const a=unique[i],b=unique[j],wa=words(a.description),wb=words(b.description);
  // Jaccard catches two broad descriptions; overlap with the shorter one catches a short new description
  // inside a long existing one ("ship it, deploy, push" against a full release skill).
  const shared=[...wa].filter((w)=>wb.has(w)),score=shared.length/(new Set([...wa,...wb]).size||1),cover=shared.length/(Math.min(wa.size,wb.size)||1);
  const phrases=[...quoted(a.description)].filter((p)=>quoted(b.description).has(p));
  if(score>=0.15||(cover>=0.35&&shared.length>=3)||phrases.length)collisions.push({a:a.name,b:b.name,score:Number(score.toFixed(2)),cover:Number(cover.toFixed(2)),shared,phrases});
 }
 collisions.sort((x,y)=>y.phrases.length-x.phrases.length||y.cover-x.cover);
 return {skills,names:unique.length,collisions,sameName,copies};
}

if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
 const given=process.argv.slice(2).map((root)=>resolve(root)),defaults=defaultRoots();
 const roots=[...new Set(given.length?given:defaults)];
 const {skills,names,collisions,sameName,copies}=inventory(roots,given.length?defaults:[]);
 const scoped=skills.filter((s)=>s.inScope),neighbours=skills.filter((s)=>!s.inScope),editable=scoped.filter((s)=>s.status==='editable').length;
 console.log(`INVENTORY | scope=${given.length?'named':'all installed'} | roots=${roots.filter(existsSync).length}/${roots.length} | skills=${scoped.length} | editable=${editable} | report-only=${scoped.length-editable} | neighbours=${neighbours.length} | names=${names} | same-name=${sameName.length} | collision-candidates=${collisions.length}`);
 for(const root of given)if(!existsSync(root))console.log(`missing ${root}`);
 for(const s of scoped)console.log(`skill ${s.name} | ${s.status} | ${s.folder}${s.real!==s.folder?` -> ${s.real}`:''} | ${s.digest}`);
 if(neighbours.length)console.log(`neighbours (read-only): ${[...new Set(neighbours.map((s)=>s.name))].sort().join(' ')}`);
 for(const c of copies)console.log(`copies ${c.name} | ${c.folder} | identical at ${c.paths.join(', ')} | reinstall after edits`);
 for(const s of sameName)console.log(`same-name ${s.name} | ${s.a} | differs from ${s.b} | ${s.effect}`);
 for(const c of collisions)console.log(`collision ${c.a} <> ${c.b} | overlap=${c.score} | cover=${c.cover}${c.phrases.length?` | same trigger: ${c.phrases.join(', ')}`:''} | shared: ${c.shared.slice(0,12).join(' ')}`);
}
